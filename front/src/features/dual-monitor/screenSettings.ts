// 방향 등록: 점이 나타난 뒤 고개를 돌리는 동안은 기다리고, 흔들림이 작은 표본만 모읍니다.
export const REGISTRATION = Object.freeze({
  // 화면이 바뀐 뒤 고개를 돌리는 동안의 표본은 버립니다.
  leadInMs: 1200,
  // 안정된 방향을 이 시간만큼 모으면 그 화면의 방향으로 등록합니다.
  collectMs: 1500,
  minSamples: 10,
  // 모으는 동안 좌우·상하 흔들림이 이보다 크면 처음부터 다시 모읍니다.
  maxSpreadDegrees: 6,
  // 이미 등록한 화면과 이보다 가까우면 아직 고개를 돌리지 않은 것으로 보고 계속 기다립니다.
  minSeparationDegrees: 10,
  // 얼굴이 이 시간보다 오래 보이지 않으면 모은 표본을 버립니다.
  maxGapMs: 500,
  // 한 화면을 이 시간 안에 등록하지 못하면 실패로 끝냅니다.
  timeoutMs: 15000,
});
// 판정: 가장 가까운 등록 방향을 고르되, 경계 근처에서 화면이 깜빡이듯 바뀌지 않게 합니다.
export const ZONE = Object.freeze({
  // 가장 가까운 화면에서도 이만큼 벗어나면 '화면 밖'(휴대폰·서류·사람 등)으로 봅니다.
  awayDegrees: 25,
  // 다른 화면이 이만큼 더 가까워야 전환 후보로 봅니다.
  switchMarginDegrees: 3,
  // 전환 후보가 이 시간 이어져야 전환으로 인정합니다. 기다린 시간도 새 화면에 넣습니다.
  switchDwellMs: 300,
  // 표본 간격이 이보다 길면 그 사이 시간은 어느 화면에도 넣지 않습니다.
  maxGapMs: 1000,
});
// 배치 안내: 충분히 관찰한 뒤에만 보여 줍니다.
export const ADVICE = Object.freeze({
  minObservedMs: 5 * 60_000,
  // 정면이 아닌 화면을 본 시간의 비율이 이 이상이면 배치를 제안합니다.
  sideShare: 0.5,
  // 정면이 아닌 한 화면을 이 시간 이상 이어서 보면 작업 위치를 제안합니다.
  longSideStreakMs: 10 * 60_000,
});
